#!/usr/bin/env python3
"""Build the content index: lessons, exercises, verification records and placeholders.

Inputs (read):
  content/lessons/*.md              authored lessons with YAML front matter
  content/verification/*.json       authored verification records
  knowledge/curriculum/coverage.json          generated coverage per competency
  knowledge/curriculum/skill-competency-map.json
  knowledge/roadmaps/consolidated-inventory.json
  knowledge/lessons/checks-report.json        generated by tools/run_content_checks.py

Outputs (generated):
  knowledge/lessons/registry.json             the index the application reads
  content/curriculum/placeholders.json        what is known about every unsourced competency

The placeholder file is the honest answer to "what happens to the 52 competencies with no source
yet". Nothing is invented for them: each placeholder carries the roadmap skill that named the
topic, why the topic matters (from the competency framework), what is scheduled around it in the
user's own plan, and exactly what source is needed. Priority is not invented either — it is taken
from the roadmap's own order, and the field says so.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

try:
    import yaml
except ImportError:  # pragma: no cover
    print(
        "PyYAML is required to read lesson front matter: install it into the project virtualenv "
        "(see requirements-dev.txt).",
        file=sys.stderr,
    )
    raise SystemExit(1)

REPO = Path(__file__).resolve().parents[1]
KB = REPO / "knowledge"
LESSONS_DIR = REPO / "content" / "lessons"
VERIFICATION_DIR = REPO / "content" / "verification"
PLACEHOLDERS_PATH = REPO / "content" / "curriculum" / "placeholders.json"
REGISTRY_PATH = KB / "lessons" / "registry.json"

FRONT_MATTER = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.S)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def normalise(value: Any) -> Any:
    """YAML turns an unquoted date into a date object; JSON needs a string.

    Dates in front matter are always written as `YYYY-MM-DD`, so converting to the ISO string
    preserves exactly what the author wrote.
    """
    if isinstance(value, dict):
        return {key: normalise(item) for key, item in value.items()}
    if isinstance(value, list):
        return [normalise(item) for item in value]
    if hasattr(value, "isoformat") and not isinstance(value, str):
        return value.isoformat()
    return value


def read_front_matter(path: Path) -> Dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    match = FRONT_MATTER.match(text)
    if not match:
        raise ValueError(f"{path.name}: no YAML front matter found")
    data = yaml.safe_load(match.group(1))
    if not isinstance(data, dict):
        raise ValueError(f"{path.name}: front matter is not a mapping")
    return normalise(data)


def load(relative: str) -> Any:
    return json.loads((KB / relative).read_text(encoding="utf-8"))


def build_placeholders(
    coverage: Dict[str, Any],
    skill_map: Dict[str, Any],
    roadmap: Dict[str, Any],
    competencies_with_lessons: set[str],
) -> Dict[str, Any]:
    skills_by_id = {skill["id"]: skill for skill in skill_map["skills"]}
    roadmap_by_id = {skill["id"]: skill for skill in roadmap["skills"]}
    order_index = {skill["id"]: index for index, skill in enumerate(roadmap["skills"])}

    placeholders: List[Dict[str, Any]] = []
    partly_covered: List[Dict[str, Any]] = []
    for entry in coverage["competencies"]:
        if entry["declared_source_status"] == "sourced":
            continue
        if entry["competency_id"] in competencies_with_lessons:
            # A competency with a lesson is not a placeholder. What is still missing for it belongs
            # on the lesson and the competency page, not in the list of things never written.
            partly_covered.append(
                {
                    "competency_id": entry["competency_id"],
                    "title": entry["name"],
                    "domain": entry["domain"],
                    "lessons": entry["lessons"],
                    "still_missing": entry["supplemental_needed"],
                    "status": "partly_covered_by_lessons",
                }
            )
            continue

        competency_skills = entry["roadmap_skills"]
        source_needs = []
        for skill_id in competency_skills:
            skill = skills_by_id.get(skill_id)
            if skill and skill.get("source_need"):
                source_needs.append({"skill": skill_id, "need": skill["source_need"]})

        related = []
        for skill_id in competency_skills:
            roadmap_skill = roadmap_by_id.get(skill_id)
            if roadmap_skill:
                related.append(
                    {
                        "skill": skill_id,
                        "name": roadmap_skill["name"],
                        "phase": roadmap_skill["phase"],
                        "study_days": roadmap_skill["schedule"]["study_days"],
                        "what_you_learn": roadmap_skill["what_you_learn"],
                    }
                )

        planned_order = [order_index[skill_id] for skill_id in competency_skills if skill_id in order_index]
        first_phase = related[0]["phase"] if related else None

        placeholders.append(
            {
                "competency_id": entry["competency_id"],
                "title": entry["name"],
                "domain": entry["domain"],
                "target_level": entry["target_level"],
                "why_it_matters": next(
                    (
                        c["why"]
                        for c in load("curriculum/competencies.json")["competencies"]
                        if c["id"] == entry["competency_id"]
                    ),
                    None,
                ),
                "declared_source_status": entry["declared_source_status"],
                "source_status_explanation": (
                    "The supplied book contributes to this topic but does not complete it. "
                    "A supplemental source is required for the parts listed below."
                    if entry["declared_source_status"] == "partial"
                    else "No source for this topic is in the repository yet."
                ),
                "supplemental_needed": entry["supplemental_needed"],
                "roadmap_skills": related,
                "roadmap_order": {
                    "first_roadmap_position": min(planned_order) + 1 if planned_order else None,
                    "note": (
                        "The platform does not invent a priority. This is the position of the "
                        "topic in the user's own roadmap, which is the only ordering information "
                        "available so far."
                    ),
                },
                "phase": first_phase,
                "what_would_unblock_it": [
                    "A supplied primary source covering the outcomes listed for this competency, "
                    "or a decision to teach it from an external source that the maintainer has "
                    "reviewed.",
                    "Practice material: exercises with verified solutions, or a decision to author "
                    "them (they would be labelled as original).",
                ],
                "status": "awaiting_sources",
                "readiness_to_render": "placeholder",
                "placeholder_means": (
                    "This entry may be shown in the interface as a planned topic with its "
                    "prerequisites, its place in the plan and the source it is waiting for. It "
                    "must never be shown with lesson content, exercises or a progress metric, "
                    "because none exists."
                ),
            }
        )

    placeholders.sort(key=lambda p: (p["roadmap_order"]["first_roadmap_position"] or 999, p["competency_id"]))

    by_domain: Dict[str, int] = {}
    for placeholder in placeholders:
        by_domain[placeholder["domain"]] = by_domain.get(placeholder["domain"], 0) + 1

    return {
        "version": "1.1.0",
        "generated_by": "tools/build_content_index.py",
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "purpose": (
            "Records every competency that cannot yet be taught, with the reason, the source it "
            "is waiting for, and its place in the user's own roadmap. These entries are what the "
            "interface shows while a topic has no material."
        ),
        "counts": {
            "placeholders": len(placeholders),
            "by_domain": by_domain,
            "unsourced_competencies_total": len(placeholders) + len(partly_covered),
            "unsourced_with_lessons": len(partly_covered),
        },
        "rule": (
            "Placeholders cover every competency that is not fully sourced and has no lesson. A "
            "competency that is partly sourced and already has a lesson is listed under "
            "'partly_covered_with_lessons' with what is still outstanding, because it is no longer "
            "an empty slot."
        ),
        "placeholders": placeholders,
        "partly_covered_with_lessons": partly_covered,
    }


def main() -> int:
    coverage = load("curriculum/coverage.json")
    skill_map = load("curriculum/skill-competency-map.json")
    roadmap = load("roadmaps/consolidated-inventory.json")

    # --- verification records ------------------------------------------------
    records = []
    for path in sorted(VERIFICATION_DIR.glob("*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        record["_file"] = str(path.relative_to(REPO))
        record["_sha256"] = sha256(path)
        records.append(record)

    # --- lessons -------------------------------------------------------------
    lessons = []
    exercises = []
    problems: List[str] = []

    for path in sorted(LESSONS_DIR.glob("*.md")):
        front = read_front_matter(path)
        lesson = front.get("lesson")
        if not isinstance(lesson, dict):
            problems.append(f"{path.name}: front matter has no 'lesson' mapping")
            continue

        lesson = dict(lesson)
        lesson["content_path"] = str(path.relative_to(REPO))
        lesson["content_sha256"] = sha256(path)
        lesson["front_matter_exercises"] = len(front.get("exercises") or [])

        record = next((r for r in records if r["id"] == lesson.get("verification_record_id")), None)
        lesson["verification_record_outcome"] = record["outcome"] if record else None
        # The displayed state is derived from the evidence, not from what the front matter claims.
        declared = lesson.get("publication_state", "draft")
        if declared in {"verified", "published"} and not record:
            problems.append(f"{lesson['id']}: claims {declared} with no verification record")
        if record and record["outcome"] != "verified" and declared in {"verified", "published"}:
            problems.append(
                f"{lesson['id']}: claims {declared} but its verification record says {record['outcome']}"
            )
        lessons.append(lesson)

        for exercise in front.get("exercises") or []:
            exercise = dict(exercise)
            exercise["lesson_id"] = lesson["id"]
            exercises.append(exercise)

    duplicate_exercise_ids = {
        e["id"] for e in exercises if [x["id"] for x in exercises].count(e["id"]) > 1
    }
    if duplicate_exercise_ids:
        problems.append(f"duplicate exercise identifiers: {sorted(duplicate_exercise_ids)}")

    # --- placeholders --------------------------------------------------------
    competencies_with_lessons = {c for lesson in lessons for c in lesson["competencies"]}
    placeholders = build_placeholders(coverage, skill_map, roadmap, competencies_with_lessons)
    PLACEHOLDERS_PATH.parent.mkdir(parents=True, exist_ok=True)
    PLACEHOLDERS_PATH.write_text(
        json.dumps(placeholders, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    # --- registry ------------------------------------------------------------
    registry = {
        "version": "1.0.0",
        "generated_by": "tools/build_content_index.py",
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "purpose": (
            "The index the application reads. It is generated from the authored lesson files and "
            "verification records, so the interface cannot show a state that the files do not "
            "support."
        ),
        "publication_state_rule": (
            "A lesson's display state comes from its verification record when one exists, and is "
            "'draft' otherwise. A record whose outcome is 'needs_revision' cannot produce a "
            "'verified' display, and the generator reports the contradiction instead of choosing."
        ),
        "lessons": lessons,
        "exercises": exercises,
        "verification_records": records,
        "placeholders": {
            "path": str(PLACEHOLDERS_PATH.relative_to(REPO)),
            "count": placeholders["counts"]["placeholders"],
            "by_domain": placeholders["counts"]["by_domain"],
        },
        "current_state": {
            "lessons_authored": len(lessons),
            "exercises_authored": len(exercises),
            "lessons_with_verification_records": len(records),
            "lessons_verified": len([r for r in records if r["outcome"] == "verified"]),
            "topics_with_placeholders": placeholders["counts"]["placeholders"],
            "note": (
                "Read this before making any claim about the platform. "
                f"{len(lessons)} lesson(s) exist; "
                f"{len([r for r in records if r['outcome'] == 'verified'])} of them are verified. "
                "The rest are marked as needing revision because at least one core check — usually "
                "source fidelity, which needs a human reader — has not been performed."
            ),
        },
        "problems": problems,
    }

    REGISTRY_PATH.write_text(json.dumps(registry, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(json.dumps(registry["current_state"], indent=2))
    print("placeholders by domain:", json.dumps(placeholders["counts"]["by_domain"]))
    if problems:
        print(f"\nproblems ({len(problems)}):")
        for problem in problems:
            print("  -", problem)
        return 1
    print("\nno consistency problems between front matter, verification records and the registry")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
